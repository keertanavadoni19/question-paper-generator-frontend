let counter = 0;
function mcq(subjectId, chapter, difficulty, text, options, answer, solution) {
  counter += 1;
  return {
    id: `QB-${String(counter).padStart(4, "0")}`,
    subjectId,
    chapter,
    type: "mcq",
    difficulty,
    text,
    options,
    answer, // index of the correct option
    solution,
    examIds: DEFAULT_EXAMS[subjectId],
    source: "bank",
    createdBy: "system",
    createdAt: "2026-06-01T10:00:00.000Z",
  };
}
function numerical(subjectId, chapter, difficulty, text, answer, solution) {
  return {
    ...mcq(subjectId, chapter, difficulty, text, [], 0, solution),
    type: "numerical",
    options: [],
    answer: String(answer),
    examIds: ["jee-main"],
  };
}

